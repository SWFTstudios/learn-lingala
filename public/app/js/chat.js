// Live chat practice: a scenario picker and a text-message conversation with a
// Claude-powered Lingala speaker. Conversations are kept on this device only.

import { SCENARIOS, SCENARIO_BY_ID } from './chat-scenarios.js';
import { LEVELS } from './course.js';
import { api } from './api.js';
import * as store from './store.js';

const KEY = 'll-chat-v1';
const XP_PER_MESSAGE = 2;
const XP_MISSION = 10;

const esc = (s) =>
  String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);

function loadChats() {
  try {
    return JSON.parse(localStorage.getItem(KEY)) || {};
  } catch {
    return {};
  }
}

function saveChats(chats) {
  try {
    localStorage.setItem(KEY, JSON.stringify(chats));
  } catch {
    // Storage full or blocked: the chat still works for this visit.
  }
}

export function clearChats() {
  try {
    localStorage.removeItem(KEY);
  } catch {
    // Nothing stored.
  }
}

const levelLabel = (id) => (id ? `Level ${LEVELS.findIndex((l) => l.id === id) + 1}+` : 'Any level');

// --- Picker -------------------------------------------------------------------

export function chatPickerHtml({ chatEnabled, signedIn, currentLevelId }) {
  const chats = loadChats();
  const levelIdx = LEVELS.findIndex((l) => l.id === currentLevelId);
  const notice =
    chatEnabled === false
      ? `<div class="card notice">💬 Live chat practice isn't switched on yet. It needs a Claude API key on the server (see the README).</div>`
      : chatEnabled && !signedIn
      ? `<a href="#/account" class="save-banner">🔒 <span><strong>Create a free account to chat.</strong> Live practice uses AI, so it's for signed-in learners.</span></a>`
      : '';

  return `
    <h1>Chat practice</h1>
    <p class="muted">Text with a Lingala speaker in real time. They'll keep to your level, correct you gently,
    and suggest what to say if you're stuck.</p>
    ${notice}
    <div class="scenarios">
      ${SCENARIOS.map((s) => {
        const started = chats[s.id]?.messages?.length;
        const stretch = s.level && LEVELS.findIndex((l) => l.id === s.level) > levelIdx;
        const locked = chatEnabled !== true || !signedIn;
        return `
          <a href="${locked ? '#/chat' : `#/chat/${s.id}`}" class="scenario ${locked ? 'locked' : ''}" ${locked ? 'aria-disabled="true"' : ''}>
            <span class="scenario-emoji" aria-hidden="true">${s.emoji}</span>
            <span class="scenario-text">
              <span class="scenario-title">${esc(s.partner)} · ${esc(s.title)}</span>
              <span class="scenario-mission">${s.mission ? `🎯 ${esc(s.mission)}` : 'Talk about anything you like.'}</span>
              <span class="scenario-meta">
                <span class="badge ${stretch ? 'badge-stretch' : 'badge-local'}">${levelLabel(s.level)}${stretch ? ' · stretch' : ''}</span>
                ${chats[s.id]?.missionDone ? '<span class="badge">✓ Mission done</span>' : started ? '<span class="badge badge-muted">In progress</span>' : ''}
              </span>
            </span>
          </a>`;
      }).join('')}
    </div>
    <p class="footnote">Your conversations stay on this device. Chat replies are generated by AI (Claude) and can
    contain mistakes — when something sounds off, check it with a native speaker.</p>`;
}

// --- Conversation ---------------------------------------------------------------

function feedbackHtml(fb) {
  if (!fb) return '';
  if (fb.verdict === 'great') return `<div class="fb fb-great">✓ Natural! ${esc(fb.note)}</div>`;
  const label = fb.verdict === 'ok' ? '👍 More natural:' : '💡 Try:';
  return `<div class="fb fb-${fb.verdict}">${label} <strong lang="ln">${esc(fb.corrected)}</strong>
    <span class="fb-note">${esc(fb.note)}</span></div>`;
}

function messageHtml(m) {
  if (m.role === 'assistant') {
    return `<button type="button" class="bubble bubble-them">
      <span class="bubble-lg" lang="ln">${esc(m.text)}</span>
      <span class="bubble-en">${esc(m.en || '')}</span></button>`;
  }
  return `<div class="msg-you"><div class="bubble bubble-you"><span class="bubble-lg" lang="ln">${esc(m.text)}</span></div>
    ${feedbackHtml(m.feedback)}</div>`;
}

export function mountChat(root, scenarioId, { onExit }) {
  const s = SCENARIO_BY_ID.get(scenarioId);
  const chats = loadChats();
  const chat = (chats[scenarioId] ??= { messages: [], suggestions: [], missionDone: false });
  let sending = false;

  root.innerHTML = `
    <div class="chat-app">
      <header class="chat-head">
        <button type="button" class="icon-btn chat-back" aria-label="Back">←</button>
        <span class="chat-avatar" aria-hidden="true">${s.emoji}</span>
        <span class="chat-who"><strong>${esc(s.partner)}</strong><span class="chat-status">${esc(s.title)}</span></span>
        <button type="button" class="chat-reset" title="Start over">New chat</button>
      </header>
      <div class="chat-log" aria-live="polite">
        <div class="chat-intro">
          <p class="setting">${esc(s.setting)}</p>
          ${s.mission ? `<div class="mission ${chat.missionDone ? 'done' : ''}">🎯 <strong>Mission:</strong> ${esc(s.mission)}</div>` : ''}
          <p class="hint">Tap any of ${esc(s.partner)}'s messages to see the English.</p>
        </div>
        <div class="chat-messages"></div>
      </div>
      <footer class="chat-foot">
        <div class="chat-suggest"></div>
        <p class="chat-error" role="alert"></p>
        <form class="chat-compose">
          <button type="button" class="key-btn" data-ch="ɛ">ɛ</button>
          <button type="button" class="key-btn" data-ch="ɔ">ɔ</button>
          <input class="chat-input" lang="ln" autocomplete="off" autocapitalize="sentences" spellcheck="false"
                 enterkeyhint="send" maxlength="400" placeholder="Write in Lingala…" aria-label="Your message">
          <button class="chat-send" aria-label="Send">➤</button>
        </form>
      </footer>
    </div>`;

  const log = root.querySelector('.chat-log');
  const list = root.querySelector('.chat-messages');
  const suggest = root.querySelector('.chat-suggest');
  const input = root.querySelector('.chat-input');
  const errorEl = root.querySelector('.chat-error');
  const sendBtn = root.querySelector('.chat-send');

  const opener = { role: 'assistant', text: s.opener.lg, en: s.opener.en };

  function draw() {
    list.innerHTML = [opener, ...chat.messages].map(messageHtml).join('') +
      (sending ? `<div class="bubble bubble-them typing" aria-label="${esc(s.partner)} is typing"><span></span><span></span><span></span></div>` : '') +
      (chat.missionDone && s.mission ? '<div class="mission-done">🏆 Mission complete! Malamu mingi. Keep chatting or try another partner.</div>' : '');
    suggest.innerHTML = (sending ? [] : chat.suggestions)
      .map((x, i) => `<button type="button" class="suggest-chip" data-i="${i}" title="${esc(x.en)}"><span lang="ln">${esc(x.lg)}</span><small>${esc(x.en)}</small></button>`)
      .join('');
    sendBtn.disabled = sending;
    log.scrollTop = log.scrollHeight;
  }

  list.addEventListener('click', (e) => e.target.closest('.bubble-them')?.classList.toggle('revealed'));
  suggest.addEventListener('click', (e) => {
    const chip = e.target.closest('.suggest-chip');
    if (!chip) return;
    input.value = chat.suggestions[Number(chip.dataset.i)].lg;
    input.focus();
  });
  root.querySelectorAll('.key-btn').forEach((b) =>
    b.addEventListener('click', () => {
      const { selectionStart: a, selectionEnd: z, value } = input;
      input.value = value.slice(0, a) + b.dataset.ch + value.slice(z);
      input.setSelectionRange(a + 1, a + 1);
      input.focus();
    }),
  );
  root.querySelector('.chat-back').addEventListener('click', onExit);
  root.querySelector('.chat-reset').addEventListener('click', () => {
    if (chat.messages.length && !confirm(`Start a new chat with ${s.partner}?`)) return;
    chat.messages = [];
    chat.suggestions = [];
    chat.missionDone = false;
    saveChats(chats);
    root.querySelector('.mission')?.classList.remove('done');
    draw();
  });

  root.querySelector('.chat-compose').addEventListener('submit', async (e) => {
    e.preventDefault();
    const text = input.value.trim();
    if (!text || sending) return;
    errorEl.textContent = '';
    const mine = { role: 'user', text };
    chat.messages.push(mine);
    input.value = '';
    sending = true;
    draw();
    try {
      const res = await api('chat', {
        method: 'POST',
        body: { scenario: s.id, messages: chat.messages.map((m) => ({ role: m.role, text: m.text })) },
      });
      mine.feedback = res.feedback;
      chat.messages.push({ role: 'assistant', text: res.reply, en: res.translation });
      chat.suggestions = res.suggestions;
      store.addXp(XP_PER_MESSAGE);
      if (res.mission_complete && s.mission && !chat.missionDone) {
        chat.missionDone = true;
        store.addXp(XP_MISSION);
        root.querySelector('.mission')?.classList.add('done');
      }
    } catch (err) {
      // Put the message back so nothing typed is lost.
      chat.messages.pop();
      input.value = text;
      errorEl.textContent = err.message;
      if (err.status === 401) errorEl.innerHTML = 'Please <a href="#/account/login">sign in again</a> to keep chatting.';
    } finally {
      sending = false;
      saveChats(chats);
      draw();
      input.focus();
    }
  });

  draw();
  setTimeout(() => input.focus(), 50);
  return () => saveChats(chats);
}

export const isScenario = (id) => SCENARIO_BY_ID.has(id);
